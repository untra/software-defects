def snake(s):
    import re
    return re.sub(r'(?<!^)(?=[A-Z])','_',s).lower()

def obj(fields):
    return {'type':'object','properties':fields,'required':list(fields),'additionalProperties':False}

def schema(t):
    if t.startswith('Vec<'): return {'type':'array','items':schema(t[4:-1])}
    if t.startswith('Option<'): return {'anyOf':[schema(t[7:-1]),{'type':'null'}]}
    if t=='String': return {'type':'string'}
    if t in ('usize','u32','u64','i64'): return {'type':'integer',**({} if t=='i64' else {'minimum':0})}
    return {'$ref':'#/$defs/'+t}

def declarations():
    d={n:obj({k:schema(t) for k,t in f.items()}) for n,f in STRUCTS.items()}
    d.update({n:{'enum':[snake(v) for v in vs]} for n,vs in ENUMS.items()})
    d.update({n:{'oneOf':[obj({'kind':{'const':snake(v)},**{k:schema(t) for k,t in f.items()}}) for v,f in vs.items()]} for n,vs in VARIANTS.items()})
    return d

def ts(t):
    if t.startswith('Vec<'): return 'Array<'+ts(t[4:-1])+'>'
    if t.startswith('Option<'): return ts(t[7:-1])+' | null'
    return {'String':'string','usize':'number','u32':'number','u64':'number','i64':'number'}.get(t,t)

def generated():
    rust=['// Generated by tasks/build_schemas.py.','use crate::model::Span;','use crate::state::Location;','use serde::{Deserialize, Serialize};']
    types=['// Generated by tasks/build_schemas.py.','export interface Span { start: number; end: number }','export interface Location { uri: string; range: Span }']
    for n,f in STRUCTS.items():
        rust += ['#[derive(Debug, Clone, Serialize, Deserialize)]','#[serde(deny_unknown_fields)]',f'pub struct {n} {{',*[f'    pub {k}: {t},' for k,t in f.items()],'}']
        types += [f'export interface {n} {{ '+ '; '.join(f'{k}: {ts(t)}' for k,t in f.items())+' }']
    for n,vs in ENUMS.items():
        rust += ['#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]','#[serde(rename_all = "snake_case")]',f'pub enum {n} {{'+','.join(vs)+'}']
        types += [f'export type {n} = '+' | '.join(json.dumps(snake(v)) for v in vs)+';']
    for n,vs in VARIANTS.items():
        rust += ['#[derive(Debug, Clone, Serialize, Deserialize)]','#[serde(tag = "kind", rename_all = "snake_case", deny_unknown_fields)]',f'pub enum {n} {{',*[v+' { '+','.join(f'{k}: {t}' for k,t in f.items())+' },' for v,f in vs.items()],'}']
        types += [f'export type {n} = '+' | '.join('{ kind: '+json.dumps(snake(v))+'; '+'; '.join(f'{k}: {ts(t)}' for k,t in f.items())+' }' for v,f in vs.items())+';']
    return {ROOT/'tooling/state-lens/src/state_contract.rs':'\n'.join(rust)+'\n', ROOT/'extensions/vscode/src/state-contract.ts':'\n'.join(types)+'\n'}

